#!/usr/bin/env node
import { build } from 'esbuild'
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, renameSync, unlinkSync } from 'node:fs'
import { dirname, join, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ampSqliteResolver, ampSqliteRoot } from './amp-sqlite-resolver.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const source = resolve(root, 'src/mcp')
const entries = readdirSync(source, { recursive: true }).filter(name => name.endsWith('.mts') && !name.endsWith('.d.mts') && (!process.argv.includes('--amp-runtime') || name.replaceAll('\\', '/') === 'amp/runtime.mts')).map(name => resolve(source, name))
const result = await build({
  absWorkingDir: root,
  entryPoints: entries,
  outdir: resolve(root, 'plugins/codex-coordination/mcp'),
  outbase: source,
  outExtension: { '.js': '.mjs' },
  bundle: true,
  // All entrypoints, including native AMP upper services, share one Store module.
  splitting: true,
  chunkNames: 'chunks/[name]-[hash]',
  platform: 'node',
  format: 'esm',
  target: 'node24',
  legalComments: 'eof',
  metafile: true,
  write: false,
  banner: { js: '// Generated from src/mcp by npm run build:server. Do not edit this file.\nimport { createRequire as __codexCreateRequire } from "node:module"; import { fileURLToPath as __codexFileURLToPath } from "node:url"; import { dirname as __codexDirname } from "node:path"; const require = __codexCreateRequire(import.meta.url); const __filename = __codexFileURLToPath(import.meta.url); const __dirname = __codexDirname(__filename);' },
  plugins: [ampSqliteResolver(), { name: 'local-modules', setup(context) {
    // Preserve shared module identity and the store's transaction queue.
    context.onResolve({ filter: /^\..*\.mjs$/ }, args => ({ path: args.path, external: true }))
  } }],
})
// Avoid rewriting unchanged bundles: Windows may still map a loaded runtime.
// Publish hashed dependencies first: a running loader must never see a new
// entrypoint before its imported chunks exist. Keep old chunks for live readers.
// Changed files are replaced atomically; this is not a whole-directory swap.
const outputRoot = resolve(root, 'plugins/codex-coordination/mcp')
const isChunk = output => relative(outputRoot, output.path).replaceAll('\\', '/').startsWith('chunks/')
const publication = [...result.outputFiles].sort((left, right) => Number(isChunk(right)) - Number(isChunk(left)))
for (const output of publication) {
  const bytes = Buffer.from(output.contents)
  if (existsSync(output.path) && readFileSync(output.path).equals(bytes)) continue
  mkdirSync(dirname(output.path), { recursive: true })
  const temporary = output.path + '.tmp-' + process.pid
  try { writeFileSync(temporary, bytes); renameSync(temporary, output.path) }
  finally { if (existsSync(temporary)) unlinkSync(temporary) }
}
const packages = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules')) continue
  let directory = dirname(resolve(root, input))
  while (directory !== dirname(directory)) {
    const manifest = join(directory, 'package.json')
    if (existsSync(manifest)) {
      const pkg = JSON.parse(readFileSync(manifest, 'utf8'))
      if (pkg.name) { packages.set(pkg.name, { pkg, directory }); break }
    }
    directory = dirname(directory)
  }
}
const notices = ['# Bundled server dependencies\n',
  '## Exact reference AMP SQLite stack (attention-manifest-protocol 0.7.1)\n\nSource and hashes: vendor/amp-sqlite/SNAPSHOT.json. Native upper AMP modules retain their installed version.\n',
  readFileSync(join(ampSqliteRoot, 'NOTICE'), 'utf8'), readFileSync(join(ampSqliteRoot, 'LICENSE'), 'utf8')]
// Publish the integrity record alongside the redistributed copied code.
const assets = resolve(root, 'plugins/codex-coordination/assets')
mkdirSync(assets, { recursive: true })
writeFileSync(join(assets, 'AMP_SQLITE_SNAPSHOT.json'), readFileSync(join(ampSqliteRoot, 'SNAPSHOT.json')))

for (const [name, { pkg, directory }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  notices.push(`## ${name} ${pkg.version}\n\nLicense: ${pkg.license ?? 'see below'}\n`)
  for (const file of readdirSync(directory).filter(name => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name))) notices.push(`### ${file}\n\n${readFileSync(join(directory, file), 'utf8')}\n`)
}
writeFileSync(join(assets, 'THIRD_PARTY_LICENSES.md'), notices.join('\n'))
console.log(`built ${entries.length} TypeScript server modules (AMP bundled from npm)`)
