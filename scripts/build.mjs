#!/usr/bin/env node
import { build } from 'esbuild'
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const source = resolve(root, 'src/mcp')
const entries = readdirSync(source, { recursive: true }).filter(name => name.endsWith('.mts') && !name.endsWith('.d.mts') && (!process.argv.includes('--amp-runtime') || name.replaceAll('\\', '/') === 'amp/runtime.mts')).map(name => resolve(source, name))
const result = await build({
  absWorkingDir: root,
  entryPoints: entries,
  outdir: resolve(root, 'plugins/codex-coordination/mcp'),
  outbase: source,
  outExtension: { '.js': '.mjs' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  legalComments: 'eof',
  metafile: true,
  banner: { js: '// Generated from src/mcp by npm run build:server. Do not edit this file.\nimport { createRequire as __codexCreateRequire } from "node:module"; import { fileURLToPath as __codexFileURLToPath } from "node:url"; import { dirname as __codexDirname } from "node:path"; const require = __codexCreateRequire(import.meta.url); const __filename = __codexFileURLToPath(import.meta.url); const __dirname = __codexDirname(__filename);' },
  plugins: [{ name: 'local-modules', setup(context) {
    // Preserve shared module identity and the store's transaction queue.
    context.onResolve({ filter: /^\..*\.mjs$/ }, args => ({ path: args.path, external: true }))
  } }],
})
const packages = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules')) continue
  let directory = dirname(resolve(root, input))
  while (directory !== dirname(directory)) {
    const manifest = join(directory, 'package.json')
    if (existsSync(manifest)) {
      const pkg = JSON.parse(readFileSync(manifest, 'utf8'))
      if (pkg.name) { packages.set(pkg.name, { pkg, directory }); break }
    }
    directory = dirname(directory)
  }
}
const notices = ['# Bundled server dependencies\n']
for (const [name, { pkg, directory }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  notices.push(`## ${name} ${pkg.version}\n\nLicense: ${pkg.license ?? 'see below'}\n`)
  for (const file of readdirSync(directory).filter(name => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name))) notices.push(`### ${file}\n\n${readFileSync(join(directory, file), 'utf8')}\n`)
}
const assets = resolve(root, 'plugins/codex-coordination/assets')
mkdirSync(assets, { recursive: true })
writeFileSync(join(assets, 'THIRD_PARTY_LICENSES.md'), notices.join('\n'))
console.log(`built ${entries.length} TypeScript server modules (AMP bundled from npm)`)
