import test from 'node:test'
import assert from 'node:assert/strict'
import { writeFileSync, readFileSync, mkdirSync, symlinkSync, truncateSync } from 'node:fs'
import { join } from 'node:path'
import { withAmpSurface } from '../plugins/codex-coordination/mcp/amp/surface.mjs'
import { makeWorkspace } from './helpers.mjs'

test('native workspace reads/outline/diff preserve bytes and enforce exact path bounds', async t => {
  const root = makeWorkspace(t), outside = makeWorkspace(t)
  writeFileSync(join(root, 'guide.md'), '\uFEFF# Heading\r\nHello 世界\r\n')
  writeFileSync(join(outside, 'private.md'), 'private')
  mkdirSync(join(root, '.git')); writeFileSync(join(root, '.git', 'config'), 'private')
  writeFileSync(join(root, 'hidden.md'), 'host excluded')
  symlinkSync(outside, join(root, 'linked'), 'junction')
  const tools = withAmpSurface([], () => root, () => ({ root, exclude: ['hidden.md'] }))
  const call = (verb, args = {}) => tools.find(tool => tool.name === 'attention_manifest_protocol_workspace.' + verb).handler(args)
  const before = readFileSync(join(root, 'guide.md'))
  const read = await call('read', { path: 'guide.md', startLine: 1, maxLines: 1 })
  assert.equal(read.text, '# Heading\n')
  assert.equal(read.snapshot.bom, true)
  assert.equal(read.snapshot.eol, '\r\n')
  assert.match(read.baseHash, /^[a-f0-9]{64}$/)
  const offset = Buffer.byteLength('# Heading\nHello ')
  assert.equal((await call('read', { path: 'guide.md', mode: 'byte', startByte: offset, endByte: offset + 3 })).text, '世')
  await assert.rejects(call('read', { path: 'guide.md', mode: 'byte', startByte: offset + 1, endByte: offset + 3 }))
  writeFileSync(join(root, 'utf16.txt'), Buffer.from('\uFEFFHello\r\n世界\r\n', 'utf16le'))
  assert.equal((await call('read', { path: 'utf16.txt', startLine: 2, maxLines: 1 })).text, '世界\n')
  writeFileSync(join(root, 'long-line.txt'), 'x'.repeat(262145))
  await assert.rejects(call('read', { path: 'long-line.txt' }), /256 KiB/)
  assert.equal((await call('read', { path: 'long-line.txt', mode: 'byte', startByte: 0, endByte: 128 })).text.length, 128)
  const outline = await call('outline', { path: 'guide.md' })
  assert.ok(outline.nodes.some(node => node.name === 'Heading'))
  const diff = await call('diff', { path: 'guide.md', expectedHash: read.baseHash, content: '# New heading\nHello 世界\n' })
  assert.equal(diff.previewOnly, true)
  assert.ok(diff.diff.hunks.length)
  assert.deepEqual(readFileSync(join(root, 'guide.md')), before)
  await assert.rejects(call('diff', { path: 'guide.md', expectedHash: 'old', content: 'bad' }), /expectedHash/)
  for (const path of ['../private.md', '/etc/passwd', 'C:/private.md', '.git/config', 'linked/private.md', 'hidden.md', '.GIT/config', 'guide.md:stream', './guide.md']) await assert.rejects(call('read', { path }))
  await assert.rejects(call('read', { path: 'guide.md', principalId: 'spoof' }))
  writeFileSync(join(root, 'large.txt'), ''); truncateSync(join(root, 'large.txt'), 16 * 1024 * 1024 + 1)
  await assert.rejects(call('read', { path: 'large.txt' }), /16 MiB/)
  const list = await call('list')
  assert.ok(list.entries.some(entry => entry.path === 'guide.md'))
  assert.ok(!list.entries.some(entry => /hidden|linked|(^|\/)\.git(\/|$)|codex-coordination/.test(entry.path)))
  assert.ok(list.entries.some(entry => entry.path === '.gitignore'))
})

test('native workspace log outline uses the upgraded AMP date and severity parser', async t => {
  const root = makeWorkspace(t)
  const content = '2026-11-07T12:34:56.789Z ERROR failed to open source\n    at parse (source.ts:1)\n2026-11-07T12:35:00.000Z INFO recovered\n'
  writeFileSync(join(root, 'server.log'), content)
  const tools = withAmpSurface([], () => root)
  const result = await tools.find(tool => tool.name === 'attention_manifest_protocol_workspace.outline').handler({ path: 'server.log' })
  const date = result.nodes.find(node => node.id.startsWith('log:date:'))
  assert.ok(date, JSON.stringify(result))
  assert.match(date.name, /2026-11-07/)
  const errors = result.nodes.find(node => node.name === 'ERROR ×1')
  assert.equal(errors.parentId, date.id)
  assert.ok(result.nodes.some(node => node.name === 'INFO ×1'))
  const failure = result.nodes.find(node => node.id.startsWith('log:entry:0:'))
  assert.equal(failure.range.endLine, 2, 'stack-trace continuation belongs to the original log entry')
  assert.equal(readFileSync(join(root, 'server.log'), 'utf8'), content)
})

test('native document outline reads bounded archive bytes without text conversion', async t => {
  const root = makeWorkspace(t)
  const zip = Buffer.alloc(22); zip.writeUInt32LE(0x06054b50)
  writeFileSync(join(root, 'empty.zip'), zip)
  const tools = withAmpSurface([], () => root)
  const result = await tools.find(tool => tool.name === 'attention_manifest_protocol_workspace.document_outline').handler({ path: 'empty.zip' })
  assert.equal(result.snapshot.binary, true)
  assert.ok(result.outline.language)
  assert.equal(result.outline.entries.length, 0)
  assert.deepEqual(readFileSync(join(root, 'empty.zip')), zip)
})
