test('host signing keys never expose private material and revocation survives reopen', async t => {
  const { host, workspace } = await fixture(t)
  const generated = await host.adapter('keys', { action: 'generate', kid: 'key.probe', signer: 'technology' })
  assert.equal('d' in generated.publicJwk, false)
  const signed = await host.adapter('keys', { action: 'call', module: 'governance', operation: 'signCanonicalValue', arguments: [{ content: 'attention' }, { $key: 'key.probe' }] })
  const verify = signature => host.adapter('keys', { action: 'call', module: 'governance', operation: 'verifyCanonicalValue', arguments: [{ content: 'attention' }, signature, { $publicKey: 'key.probe' }] })
  assert.equal((await verify(signed.result)).result, true)
  assert.equal((await verify((signed.result[0] === 'A' ? 'B' : 'A') + signed.result.slice(1))).result, false)
  await host.adapter('keys', { action: 'revoke', kid: 'key.probe' })
  await host.close(); await host.select(workspace)
  await assert.rejects(host.adapter('keys', { action: 'call', module: 'governance', operation: 'signCanonicalValue', arguments: [{ content: 'attention' }, { $key: 'key.probe' }] }), /unavailable for signing/)
  const listed = JSON.stringify(await host.adapter('keys', { action: 'list' }))
  assert.equal(listed.includes('private_jwk'), false)
  assert.equal(listed.includes('"d":'), false)
})

