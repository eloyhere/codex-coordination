  assert.equal((await host.registry({ registry: 'sqlDialects', action: 'get', id: 'mysql' })).entry.label, 'Changed MySQL')
  await host.registry({ registry: 'sqlDialects', action: 'remove', id: 'mysql', expectedVersion: 1 })
  assert.equal((await host.registry({ registry: 'sqlDialects', action: 'get', id: 'mysql' })).entry, null)
