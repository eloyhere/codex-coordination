async function fixture(t, options = {}, inputs = { 'probe.ts': 'export const probe = 1\n' }) {
  const directory = mkdtempSync(join(tmpdir(), 'codex-amp-domains-'))
  const workspace = join(directory, 'repo')
  mkdirSync(workspace)
  for (const [path, content] of Object.entries(inputs)) { const absolute = join(workspace, path); mkdirSync(join(absolute, '..'), { recursive: true }); writeFileSync(absolute, content) }
  const host = new AmpHost({ databasePath: join(directory, 'host.sqlite'), ...options })
  t.after(async () => { await host.close(); rmSync(directory, { recursive: true, force: true }) })
  await host.select(workspace)
  return { host, workspace, directory }
}
const create = async (host, module, name, args = []) => (await host.domain({ action: 'create', module, name, arguments: args })).result.$ampRef
const invoke = async (host, resource, method, args = []) => (await host.domain({ action: 'invoke', resource, method, arguments: args })).result

test('published scanners project nested projects, compiler calls/imports and document knowledge', async t => {
  const { host, workspace } = await fixture(t, {}, {
    'package.json': '{"name":"root"}', 'src/a.ts': 'export function add(x:number){ return x+1 }',
    'src/b.ts': 'import {add} from "./a"; export const result = add(1);',
    'packages/child/package.json': '{"name":"child","dependencies":{"root":"workspace:*"}}',
    'packages/child/index.ts': 'export const child = 1', 'guide.md': '# Guide\nUseful source facts.\n',
    'generated.mjs': '// Generated from src/mcp by npm run build:server. Do not edit this file.\nexport function bundledDuplicate() {}',
  })
  const capabilities = await host.call('amp_tool_global_capabilities', {})
  assert.equal(capabilities.ok, true)
  assert.equal(capabilities.data.projectIds.length, 2)
  const tree = await host.call('amp_tool_workspace_tree', { revision: capabilities.revision, parentId: 'project:.' })
  assert.equal(tree.ok, true)
  const query = await host.call('amp_tool_workspace_query', { revision: capabilities.revision, text: 'add', limit: 100 })
  assert.equal(query.ok, true, JSON.stringify(query))
  assert.ok(query.data.candidates.length > 0)
  assert.ok(host.status().diagnostics.some(item => item.uri === 'generated.mjs' && item.code === 'generated_artifact'))
  assert.equal((await host.call('amp_tool_filesystem_read', { path: 'generated.mjs' })).ok, true)
  writeFileSync(join(workspace, 'new.ts'), 'export const fresh = 1')
  const refreshed = await host.refresh()
  assert.notEqual(refreshed.revision, capabilities.revision)
})

test('domain computations use native algorithms and typed BigInt/byte/iterator values', async t => {
  const { host } = await fixture(t)
  const args = [['a', 'b', 'a'], ['a', 'b', 'b']]
  const result = await host.domain({ action: 'call', module: 'evaluation', name: 'cohenKappa', arguments: args })
  assert.equal(result.result, amp.evaluation.cohenKappa(...args))
  const lines = await host.domain({ action: 'call', module: 'syntax', name: 'countLines', arguments: ['a\nb\n'] })
  assert.deepEqual(lines.result, { $bigint: amp.syntax.countLines('a\nb\n').toString() })
  const bytes = await host.domain({ action: 'call', module: 'syntax', name: 'encodeText', arguments: ['注意'] })
  assert.equal(Buffer.from(bytes.result.$bytes, 'base64').toString(), '注意')
  const map = await create(host, 'structure', 'OrderedMap')
  await invoke(host, map, 'set', ['a', 1])
  assert.deepEqual(await invoke(host, map, 'entries'), [['a', 1]])
  const comparator = await host.domain({ action: 'call', module: 'structure', name: 'reverseComparator', arguments: [{ $ampFunction: { module: 'structure', name: 'compareNumbers' } }] })
  assert.ok(await invoke(host, comparator.result.$ampRef, '$call', [1, 2]) > 0)
  await assert.rejects(host.domain({ action: 'call', module: 'semantic', name: 'sha256Hex', arguments: [123] }), { code: 'INVALID_ARGUMENT' })
})

test('delegation enforces native attenuation/fencing and survives a database reopen', async t => {
  const { host, workspace } = await fixture(t)
  const resource = await create(host, 'delegate', 'TeamRuntime', [{}])
  const input = { granter: 'parent', delegatee: 'child', goalDigest: `sha256:${'a'.repeat(64)}`, scope: ['read'], budget: { tokens: 100 }, deadline: '2099-01-01T00:00:00Z', mayRedelegate: true, depth: 0 }
  const delegation = await invoke(host, resource, 'createDelegation', [input])
  await assert.rejects(invoke(host, resource, 'createDelegation', [{ ...input, granter: 'child', delegatee: 'grandchild', parent: delegation.id, depth: 1, budget: { tokens: 101 } }]), /exceeds parent/)
  const lease = await invoke(host, resource, 'issueLease', [delegation.id, { taskId: 'task', holder: 'child', goalDigest: input.goalDigest, budget: { tokens: 50 }, deadline: input.deadline }])
  await assert.rejects(invoke(host, resource, 'assertWriter', [lease.id, lease.fence + 1]), /stale|fence/i)
  await invoke(host, resource, 'reserve', [lease.id, { tokens: 20 }])
  await invoke(host, resource, 'settle', [lease.id, { tokens: 10 }])
  await invoke(host, resource, 'complete', [lease.id])
  await host.close(); await host.select(workspace)
  assert.equal((await invoke(host, resource, 'lease', [lease.id])).status, 'done')
  assert.equal((await invoke(host, resource, 'usage', [lease.id])).spent.tokens, 10)
})

